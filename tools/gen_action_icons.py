"""Regenerates the Zinc toolbar action icons from Material Symbols.

The icons are Android vector drawables converted from the "Material Symbols
Outlined" SVGs published at github.com/google/material-design-icons (Apache
License 2.0). Material Symbols use a 960x960 viewport shifted up by 960, so
each path is wrapped in a group translated back down.

Usage: tools/gen_action_icons.py [--svg-dir DIR]
Without --svg-dir the SVGs are downloaded from raw.githubusercontent.com.
"""

import argparse
import os
import re
import sys
import urllib.request

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_OUT_DIR = os.path.join(_ROOT, 'overlay', 'chrome', 'browser', 'ui', 'android',
                        'toolbar', 'java', 'res', 'drawable')
_URL = ('https://raw.githubusercontent.com/google/material-design-icons/'
        'master/symbols/web/{name}/materialsymbolsoutlined/{name}{fill}_24px.svg')

# drawable name -> (material symbol name, filled)
ICONS = {
    'zinc_ic_back': ('arrow_back', False),
    'zinc_ic_forward': ('arrow_forward', False),
    'zinc_ic_reload': ('refresh', False),
    'zinc_ic_stop': ('close', False),
    'zinc_ic_home': ('home', False),
    'zinc_ic_new_tab': ('add', False),
    'zinc_ic_tab_switcher': ('check_box_outline_blank', False),
    'zinc_ic_close_tab': ('tab_close', False),
    'zinc_ic_recent_tabs': ('devices', False),
    'zinc_ic_share': ('share', False),
    'zinc_ic_bookmark_page': ('star', False),
    'zinc_ic_bookmark_page_filled': ('star', True),
    'zinc_ic_find_in_page': ('find_in_page', False),
    'zinc_ic_desktop_site': ('desktop_windows', False),
    'zinc_ic_desktop_site_filled': ('desktop_windows', True),
    'zinc_ic_translate': ('translate', False),
    'zinc_ic_reader_mode': ('chrome_reader_mode', False),
    'zinc_ic_print': ('print', False),
    'zinc_ic_add_to_home_screen': ('add_to_home_screen', False),
    'zinc_ic_page_info': ('info', False),
    'zinc_ic_copy_link': ('link', False),
    'zinc_ic_bookmarks': ('bookmarks', False),
    'zinc_ic_history': ('history', False),
    'zinc_ic_downloads': ('download', False),
    'zinc_ic_quick_delete': ('delete_history', False),
    'zinc_ic_settings': ('settings', False),
    'zinc_ic_extensions': ('extension', False),
    'zinc_ic_manage_extensions': ('build', False),
    'zinc_ic_web_store': ('storefront', False),
    'zinc_ic_more_vert': ('more_vert', False),
    'zinc_ic_check': ('check', False),
}

_TEMPLATE = '''<?xml version="1.0" encoding="utf-8"?>
<!--
Copyright 2026 The Zinc Authors
Use of this source code is governed by a BSD-style license that can be
found in the LICENSE file.

Generated by tools/gen_action_icons.py from the Material Symbols icon
"{symbol}"{fill_note} (Apache License 2.0). Do not edit by hand.
-->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="960"
    android:viewportHeight="960"
    android:tint="?attr/colorControlNormal">
    <group android:translateY="960">
        <path
            android:fillColor="@android:color/white"
            android:pathData="{path}" />
    </group>
</vector>
'''


def _read_svg(name, filled, svg_dir):
    fill = '_fill1' if filled else ''
    if svg_dir:
        with open(os.path.join(svg_dir, f'{name}{fill}_24px.svg')) as f:
            return f.read()
    with urllib.request.urlopen(_URL.format(name=name, fill=fill)) as resp:
        return resp.read().decode('utf-8')


def _extract_path(svg):
    if 'viewBox="0 -960 960 960"' not in svg:
        raise ValueError('Unexpected viewBox; not a Material Symbols SVG')
    paths = re.findall(r'<path[^>]*\sd="([^"]+)"', svg)
    if len(paths) != 1:
        raise ValueError(f'Expected exactly one path, found {len(paths)}')
    return paths[0]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--svg-dir',
                        help='Directory with <symbol>[_fill1]_24px.svg files')
    args = parser.parse_args()

    os.makedirs(_OUT_DIR, exist_ok=True)
    for drawable, (symbol, filled) in sorted(ICONS.items()):
        path = _extract_path(_read_svg(symbol, filled, args.svg_dir))
        content = _TEMPLATE.format(symbol=symbol,
                                   fill_note=' (filled)' if filled else '',
                                   path=path)
        with open(os.path.join(_OUT_DIR, drawable + '.xml'), 'w') as f:
            f.write(content)
        print(f'Wrote {drawable}.xml')
    return 0


if __name__ == '__main__':
    sys.exit(main())
